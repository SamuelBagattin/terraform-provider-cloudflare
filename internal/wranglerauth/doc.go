// This package is intentionally NOT code-generated.

// Package wranglerauth lets the provider authenticate with the OAuth session
// of a local `wrangler login` instead of an API token.
//
// The token always comes from `wrangler auth token --json` (wrangler >=
// 4.57.0). This package never reads or writes wrangler's credential files or
// keyring entries itself: wrangler stays the only owner of the OAuth state,
// including refresh-token rotation.
//
// The pieces are:
//
//   - [TokenSource] runs wrangler and keeps the token in memory for a short
//     TTL. Concurrent callers share a single wrangler process (singleflight),
//     and an advisory file lock serialises wrangler runs across provider
//     processes, so two refreshes never race on the same refresh token.
//   - [TokenSource.Middleware] is a cloudflare-go option.Middleware that sets
//     the Authorization header on every request, removes the legacy
//     X-Auth-* headers, and on a 401 refreshes the token and replays the
//     request once when its body can be replayed.
//   - [ProviderModel], [AddSchemaAttributes] and [Configure] hold the
//     provider-facing glue, so that internal/provider.go (generated by
//     Stainless) only needs a few clearly delimited lines.
//
// The token never appears in logs, diagnostics, errors or state: wrangler's
// standard output (where the token is printed) is parsed and dropped, and
// only its redacted standard error is ever surfaced.
package wranglerauth
